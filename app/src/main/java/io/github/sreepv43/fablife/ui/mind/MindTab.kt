/** Explore → Mind: breathing, guided sessions, sounds and the focus, journal and Top 3 tools. */
@Composable
fun MindTab(vm: AppViewModel, state: AppState, nav: NavHostController) {
    val audio = vm.content.audio
    LazyColumn(
        contentPadding = PaddingValues(16.dp), verticalArrangement = Arrangement.spacedBy(10.dp),
        horizontalAlignment = Alignment.CenterHorizontally, modifier = Modifier.fillMaxWidth(),
    ) {
        item { Section("Breathe") }
        audio.breathing.forEach { b ->
            item(key = "b-${b.id}") { Entry(b.name, "${b.defaultMinutes} min · ${b.description}") { nav.navigate(Routes.breathing(b.id)) } }
        }
        SessionCategory.entries.forEach { category ->
            val sessions = audio.sessions.filter { it.category == category }
            if (sessions.isNotEmpty()) {
                item(key = "h-$category") { Section("Guided: ${category.label()}") }
                sessions.forEach { s ->
                    item(key = "g-${s.id}") { Entry(s.title, "${s.minutes} min · ${s.description}") { nav.navigate(Routes.guided(s.id)) } }
                }
            }
        }
        item { Section("Sounds") }
        item { Entry("Ambient sounds", "Rain, ocean, fan, noise and a calm drone. Generated by your phone, with a sleep timer.") { nav.navigate(Routes.SOUNDS) } }
        item { Section("Tools") }
        item { Entry("Focus timer", "Work in focused blocks with short breaks.") { nav.navigate(Routes.focus()) } }
        item { Entry("Journal", "Gratitude, reflection and mood. Stays on your device.") { nav.navigate(Routes.journal()) } }
        item { Entry("Top 3 for today", "Pick the three things that matter most.") { nav.navigate(Routes.top3()) } }
    }
}

@Composable
private fun Section(text: String) {
    SectionTitle(text, Modifier.fillMaxWidth().widthIn(max = 640.dp))
}

@Composable
private fun Entry(title: String, subtitle: String, onClick: () -> Unit) {
    Card(
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceContainer),
        modifier = Modifier.fillMaxWidth().widthIn(max = 640.dp).clickable(role = Role.Button, onClick = onClick),
    ) {
        Column(Modifier.padding(16.dp)) {
            Text(title, style = MaterialTheme.typography.titleMedium)
            Text(subtitle, style = MaterialTheme.typography.bodyMedium)
        }
    }
}
